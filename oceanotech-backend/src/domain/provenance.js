/**
 * provenance.js
 * AquaTwins — Data provenance constants.
 *
 * Every data value in AquaTwins must carry a source tag.
 * This module defines the canonical provenance labels used throughout
 * the entire system (backend, frontend, API responses, stored readings).
 *
 * RULE: Never present a SIMULATION value as a SENSOR value.
 *       Never present an ESTIMATED value as an OBSERVED value.
 *       Never present a PREDICTED value as a current value.
 */

'use strict';

/**
 * Data source: where did this value originate?
 */
const DataSource = Object.freeze({
  SIMULATION: 'SIMULATION',   // Generated by PhysicalSystemSimulator
  SENSOR:     'SENSOR',       // Measured by a physical sensor device
  CAMERA:     'CAMERA',       // Derived from computer vision pipeline
  MANUAL:     'MANUAL',       // Entered by a human operator
  API:        'API',          // Received from an external REST/MQTT API
  ESTIMATED:  'ESTIMATED',    // Computed by the State Estimation Engine
  PREDICTED:  'PREDICTED',    // Forecast by the Prediction Engine
  DERIVED:    'DERIVED',      // Calculated from other observed values
});

/**
 * State type: what does this value represent in time?
 */
const StateType = Object.freeze({
  OBSERVED:  'OBSERVED',    // A value measured or received now
  ESTIMATED: 'ESTIMATED',   // A value inferred from model + observations
  PREDICTED: 'PREDICTED',   // A value forecast for a future time
  SIMULATED: 'SIMULATED',   // A value produced entirely by simulation
});

/**
 * System operating mode.
 * The platform transitions: SIMULATION → HYBRID → LIVE.
 */
const TwinMode = Object.freeze({
  SIMULATION: 'SIMULATION',   // All data from PhysicalSystemSimulator
  HYBRID:     'HYBRID',       // Mix of real sensors and simulation fill-ins
  LIVE:       'LIVE',         // All data from real sensors
  OFFLINE:    'OFFLINE',      // Connection lost; using last valid twin state
  DEGRADED:   'DEGRADED',     // Partial data; some sensors unavailable
});

/**
 * Quality status for a sensor reading.
 */
const QualityStatus = Object.freeze({
  VALID:              'VALID',
  VALID_WITH_WARNINGS:'VALID_WITH_WARNINGS',
  INVALID:            'INVALID',
  STALE:              'STALE',
  SIMULATED:          'SIMULATED',
  ESTIMATED:          'ESTIMATED',
});

/**
 * Model validation status.
 * NEVER use VALIDATED unless evidence exists.
 */
const ModelStatus = Object.freeze({
  EXPERIMENTAL:        'EXPERIMENTAL',
  CALIBRATION_PENDING: 'CALIBRATION_PENDING',
  VALIDATED:           'VALIDATED',
  PRODUCTION:          'PRODUCTION',
  DEPRECATED:          'DEPRECATED',
});

module.exports = { DataSource, StateType, TwinMode, QualityStatus, ModelStatus };
